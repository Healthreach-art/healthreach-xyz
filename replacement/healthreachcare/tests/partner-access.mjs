import assert from 'node:assert/strict';
import fs from 'node:fs';
import {postApprovalSetupRequired} from '../lib/partner-approval.mjs';
const landing=fs.readFileSync('components/public-landing.jsx','utf8');
const app=fs.readFileSync('app/page.jsx','utf8');
const auth=fs.readFileSync('components/demo-entry.jsx','utf8');
const authRoutes=fs.readFileSync('lib/auth-entry.mjs','utf8');
const roleLogin=fs.readFileSync('app/partners/login/page.jsx','utf8');
const roleSignup=fs.readFileSync('app/partners/signup/page.jsx','utf8');
const homecareLogin=fs.readFileSync('app/homecare/login/page.jsx','utf8');
const accountLayout=fs.readFileSync('components/account-layout.jsx','utf8');
const accountWorkspace=fs.readFileSync('components/account-workspace.jsx','utf8');
assert.match(landing,/href=\"\/partners\"/);
assert.match(landing,/export function PartnerPortal/);
for(const role of ['Pharmacy','Doctor','Driver'])assert(landing.includes(`role:'${role}'`));
assert.match(landing,/role==='Homecare'\?'\/homecare\/login':'\/partners\/login\?role='\+encodeURIComponent\(role\)/);
assert.match(landing,/href=\{'\/partners\/signup\?role='\+encodeURIComponent\(role\)\}/);
assert(landing.includes("role==='Homecare'?'/homecare/login'"));
assert(!landing.includes("role:'Homecare',href:'/partners/login"));
assert.match(landing,/Open Partner Portal/);
assert.match(app,/partnerHub\?<PartnerPortal selectedRole=\{initialPartnerRole\}\/>/);
assert.match(auth,/partner\?\(signup\?'\/partners\/login':'\/partners\/signup'\)/);
assert.match(roleLogin,/query\?\.role/);
assert.match(roleSignup,/query\?\.role/);
assert.match(authRoutes,/\['\/login','\/signup','\/partners\/login','\/partners\/signup'/);
assert(!authRoutes.includes("'/partners',"));
assert(homecareLogin.includes('initialHomecare'));
for(const role of ['Pharmacy','Driver'])assert.equal(postApprovalSetupRequired(role,'Approved'),false);
for(const role of ['Pharmacy','Driver'])assert.equal(postApprovalSetupRequired(role,'Pending verification'),true);
assert.match(app,/target==='Onboarding'&&!postApprovalSetupRequired\(role,s\.onboardingStatus\)/);
assert.match(app,/resolved\.page==='Onboarding'&&!postApprovalSetupRequired\(latest\.session\.role,latest\.onboardingStatus\)/);
assert.match(accountLayout,/target==='Onboarding'&&!postApprovalSetupRequired\(role,application\?\.status\|\|status\)/);
assert.match(accountWorkspace,/showApprovalSetup\?\[\{icon:FileText,title:'Administrator approval'/);
assert.match(auth,/homecareOnly\?'Homecare staff sign in'/);
assert.match(auth,/homecareOnly\?'Use your authorized HealthReachCare Homecare staff account\.'/);
assert.match(auth,/!adminOnly&&!homecareOnly/);
console.log('Partner access assertions passed: single approval unlocks Pharmacy and Driver operations without post-approval onboarding; partner entry and Homecare staff restrictions remain intact.');
